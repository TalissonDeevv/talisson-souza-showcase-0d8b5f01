export const STUDIO_MODULE_BY_KEY: ReadonlyMap<string, StudioModuleDefinition> = new Map(
  STUDIO_MODULES.map((moduleDefinition) => [moduleDefinition.key, moduleDefinition as StudioModuleDefinition]),
);

export function getStudioModule(moduleKey: string): StudioModuleDefinition | null {
  return STUDIO_MODULE_BY_KEY.get(moduleKey) ?? null;
}

export function listStudioModulesByArea(area: StudioModuleDefinition["area"]) {
  return STUDIO_MODULES.filter((moduleDefinition) => moduleDefinition.area === area);
}
